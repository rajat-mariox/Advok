/** GET /admin/learning/search?q=&court= — CourtListener opinion search. */
export async function adminSearch(req: Request, res: Response) {
  const q = str(req.query.q, 200);
  const court = str(req.query.court, 40);
  if (!q) return res.status(400).json({ error: 'q is required' });
  try {
    const results = await searchOpinions(q, court);
    const existing = new Set(studies(getDb()).map((c) => c.clusterId));
    return res.json({
      results: results.map((r) => ({ ...r, alreadyAdded: existing.has(r.clusterId) })),
      fullTextAvailable: hasCourtListenerToken(),
    });
  } catch (err) {
    return res
      .status(502)
      .json({ error: err instanceof Error ? err.message : 'CourtListener search failed' });
  }
}

