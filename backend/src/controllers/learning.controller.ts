function studies(db: DbShape): CaseStudyRecord[] {
  db.caseStudies ??= [];
  return db.caseStudies;
}

const str = (v: unknown, max = 2000) => (typeof v === 'string' ? v.trim().slice(0, max) : '');

/** Card shape for lists (no opinion text — that can be hundreds of KB). */
function toCard(c: CaseStudyRecord) {
  return {
    id: c.id,
    clusterId: c.clusterId,
    title: c.title,
    court: c.court,
    courtId: c.courtId,
    dateFiled: c.dateFiled,
    year: c.dateFiled ? c.dateFiled.slice(0, 4) : '',
    citation: c.citation,
    docketNumber: c.docketNumber,
    judges: c.judges,
    tag: c.tag,
    level: c.level,
    summary: c.summary,
    principle: c.principle,
    hasFullText: !!c.opinionText,
    hasSyllabus: !!c.syllabus,
    hasNotes: !!c.notes,
    mins: c.mins,
    published: c.published,
    sortOrder: c.sortOrder,
    reads: c.reads,
    addedAt: c.addedAt,
    updatedAt: c.updatedAt,
  };
}

function defaultPrinciple(tag: string): string {
  return (
    `This case set an important precedent in ${tag || 'US law'}. It is frequently cited in ` +
    'later rulings and remains a cornerstone of legal education in the United States.'
  );
}

// ------------------------------------------------------------- student / app

/** GET /learning/cases — published cases, in admin order. */
export function listPublished(_req: AuthedRequest, res: Response) {
  const list = studies(getDb())
    .filter((c) => c.published)
    .sort((a, b) => a.sortOrder - b.sortOrder || b.addedAt.localeCompare(a.addedAt));
  return res.json({ cases: list.map(toCard) });
}

/** GET /learning/cases/:id — one published case with its full text. Counts a read. */
export function getPublished(req: AuthedRequest, res: Response) {
  const db = getDb();
  const c = studies(db).find((x) => x.id === req.params.id && x.published);
  if (!c) return res.status(404).json({ error: 'Case not found' });
  c.reads += 1;
  saveDb();
  publishToAll('content');
  return res.json({
    case: {
      ...toCard(c),
      syllabus: c.syllabus ?? '',
      opinionText: c.opinionText ?? '',
      notes: c.notes ?? null,
    },
  });
}

/**
 * POST /learning/cases/:id/notes — structured study notes for a published
 * case. Generated by ADVOK AI on first request and cached; later requests
 * return the cached notes instantly.
 */
export async function getOrGenerateNotes(req: AuthedRequest, res: Response) {
  const db = getDb();
  const c = studies(db).find((x) => x.id === req.params.id && x.published);
  if (!c) return res.status(404).json({ error: 'Case not found' });
  if (c.notes) return res.json({ notes: c.notes, cached: true });
  if (!isAiConnected()) {
    return res.status(503).json({ error: 'ADVOK AI is not connected yet' });
  }
  if (!hasCaseText(c)) {
    return res.status(409).json({ error: 'This case has no text to build notes from yet' });
  }
  try {
    c.notes = await generateCaseNotes(c);
    c.updatedAt = new Date().toISOString();
    saveDb();
    return res.json({ notes: c.notes, cached: false });
  } catch (err) {
    return res.status(502).json({ error: err instanceof Error ? err.message : 'Notes failed' });
  }
}

